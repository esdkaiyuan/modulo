function bc(code: string, name: string, hex: string, finish: BeadColor['finish'] = 'opaque'): BeadColor {
  const value = parseInt(hex.slice(1), 16);
  return {
    code,
    name,
    hex,
    r: (value >> 16) & 0xff,
    g: (value >> 8) & 0xff,
    b: value & 0xff,
    finish
  };
}
